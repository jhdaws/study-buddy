// Prints SQL that upserts every place in data/campus_places.json into
// `locations` (place_id = the place's `vu-` id). Track M, US-02.
//
// Migrations are never edited once applied, so after changing the list:
//   npx supabase migration new campus_places_<what changed>
//   node scripts/campus-locations-sql.mjs > supabase/migrations/<that file>
// Upserting is safe to repeat: a moved place gets its new coordinates, and
// sessions keep pointing at the same row. A place REMOVED from the list keeps
// its row (sessions may reference it); the picker just stops offering it.
//
// Plain Node, deterministic output (the file's order, no timestamps).

import { readFileSync } from "node:fs";

const { source, places } = JSON.parse(
  readFileSync(new URL("../data/campus_places.json", import.meta.url), "utf8"),
);

const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;
const coord = (n) => {
  if (typeof n !== "number" || !Number.isFinite(n)) throw new Error(`bad coordinate ${n}`);
  return n.toFixed(6);
};

const rows = places.map(
  (p) => `  (${quote(p.id)}, ${coord(p.lat)}, ${coord(p.lng)})`,
);

process.stdout.write(`-- Track M · US-02 · The curated campus places as \`locations\` rows.
-- GENERATED by scripts/campus-locations-sql.mjs from data/campus_places.json.
-- Coordinates: ${source}.
--
-- resolvePlace() (src/lib/places.ts) maps a picked \`vu-\` id to its row here,
-- read as the signed-in user; it never writes these and never stores a
-- browser's coordinates. Reverses ADR 0008 rule 7 -- see the 2026-10-20 note.
-- Data only: no schema change, so database.types.ts is unchanged.

insert into public.locations (place_id, lat, lng)
values
${rows.join(",\n")}
on conflict (place_id) do update
  set lat = excluded.lat,
      lng = excluded.lng,
      validated_at = now();
`);
